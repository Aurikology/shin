// linux/make-units.mjs -- writes the oneshot job units and their timers under linux/systemd/ from one table,
// so the schedules stay in step with the launchd daemons they replace (mac/launchd-daemons/*.plist).
//
//   node linux/make-units.mjs            rewrite the files
//   node linux/make-units.mjs --check    exit 1 when a file on disk differs from the table
//
// pexi-server, pexi-deploy (+timer), pexi-tunnel and pexi-alert@ are written by hand (they are not plain jobs).

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), 'systemd');
const LIVE = '/opt/pexi/live';
const ENV = '/etc/pexi/pexi.env';
const SH = '/bin/sh';
const NODE = '/usr/local/bin/node';

/**
 * name        unit name pexi-<name>
 * twin        the launchd label it replaces
 * when        systemd OnCalendar= (local time, America/Toronto), or every = OnUnitActiveSec
 * exec        the command line
 * timeout     TimeoutStartSec
 * memoryMax   cgroup cap so a collector is the thing the kernel kills, never the server
 * alert       OnFailure= pexi-alert@ (off for the dead-man ping, which would spam every minute if its URL were unset)
 */
export const JOBS = [
  { name: 'integrity', twin: 'com.shin.integrity', desc: 'nightly PRAGMA integrity_check on every database and the free-disk check', when: '*-*-* 03:30:00', exec: `${SH} ${LIVE}/mac/run-job.sh integrity`, timeout: '30min', cwd: `${LIVE}/mac` },
  { name: 'backup', twin: 'com.shin.backup', desc: 'nightly backup of the live databases, 14 nights kept (mac/07-backup.sh)', when: '*-*-* 04:00:00', exec: `${SH} ${LIVE}/mac/07-backup.sh ${ENV}`, timeout: '1h', cwd: `${LIVE}/mac` },
  { name: 'offsite', twin: 'com.shin.offsite', desc: 'copy the night\'s backup to the encrypted off-site restic repository', when: '*-*-* 04:45:00', exec: `${SH} ${LIVE}/mac/14-offsite-backup.sh`, timeout: '1h', cwd: `${LIVE}/mac` },
  { name: 'logrotate', twin: 'com.shin.logrotate', desc: 'rotate the data-folder logs, keep 14 days (journald caps the server log itself)', when: '*-*-* 05:00:00', exec: `/usr/sbin/logrotate -s /var/lib/pexi/logrotate.state ${LIVE}/linux/logrotate.conf`, timeout: '10min', cwd: '/var/lib/pexi', post: `${NODE} ${LIVE}/mac/lib/health.mjs ok logrotate rotated by pexi-logrotate` },
  { name: 'hammer', twin: 'com.shin.hammer', desc: 'weekly Project Hammer price refresh (needs about 5 GB free)', when: 'Sun *-*-* 05:30:00', exec: `${SH} ${LIVE}/mac/hammer-refresh.sh ${ENV}`, timeout: '3h', memoryMax: '3G', cwd: LIVE, collector: true },
  { name: 'restoretest', twin: 'com.shin.restoretest', desc: 'weekly: restore the newest off-site copy into a temp folder and check it', when: 'Sun *-*-* 06:30:00', exec: `${SH} ${LIVE}/mac/15-restore-test.sh`, timeout: '2h', memoryMax: '2G', cwd: `${LIVE}/mac` },
  { name: 'openprices', twin: 'com.shin.openprices', desc: 'weekly Open Prices (Open Food Facts shelf prices) refresh, CAD and USD', when: 'Sun *-*-* 07:30:00', exec: `${SH} ${LIVE}/mac/openprices-refresh.sh ${ENV}`, timeout: '3h', memoryMax: '2G', cwd: LIVE, collector: true },
  { name: 'kroger', twin: 'com.shin.kroger', desc: 'daily Kroger shelf-price refresh, 6,000 product calls a run', when: '*-*-* 08:30:00', exec: `${SH} ${LIVE}/mac/kroger-refresh.sh ${ENV}`, timeout: '3h', memoryMax: '1G', cwd: LIVE, collector: true },
  { name: 'deadman', twin: 'com.shin.deadman', desc: 'every 60 s: read /api/health and ping the outside dead-man service (Healthchecks)', every: '60s', exec: `${NODE} ${LIVE}/scripts/deadman-probe.mjs`, timeout: '45s', cwd: LIVE, alert: false, post: `-${NODE} ${LIVE}/linux/alert.mjs ok server-crash` },
];

function service(j) {
  const L = [];
  L.push(`# Generated by linux/make-units.mjs; edit the table there, not this file.`);
  L.push(`# launchd twin: ${j.twin}${j.collector ? ' (a collector: enabled only after the datacentre-IP probe passes, see linux/CUTOVER.md)' : ''}`);
  L.push('');
  L.push('[Unit]');
  L.push(`Description=Pexi ${j.name}: ${j.desc}`);
  L.push('After=network-online.target');
  L.push('Wants=network-online.target');
  if (j.alert !== false) L.push('OnFailure=pexi-alert@%n.service');
  L.push('');
  L.push('[Service]');
  L.push('Type=oneshot');
  L.push('User=pexi');
  L.push('Group=pexi');
  L.push('UMask=0077');
  L.push(`WorkingDirectory=${j.cwd}`);
  L.push(`EnvironmentFile=${ENV}`);
  L.push(`Environment=SHIN_CONFIG_FILE=${ENV}`);
  L.push('Environment=NODE_NO_WARNINGS=1');
  L.push(`ExecStart=${j.exec}`);
  // A run that works clears any outside alert an earlier failed run raised (a no-op, no network, when none was raised).
  if (j.alert !== false) L.push(`ExecStartPost=-${NODE} ${LIVE}/linux/alert.mjs ok ${j.name}`);
  if (j.post) L.push(`ExecStartPost=${j.post}`);
  L.push(`TimeoutStartSec=${j.timeout}`);
  if (j.memoryMax) L.push(`MemoryMax=${j.memoryMax}`);
  L.push('Nice=10');
  L.push('IOSchedulingClass=idle');
  L.push('NoNewPrivileges=yes');
  L.push('ProtectSystem=full');
  L.push('PrivateTmp=yes');
  L.push(`SyslogIdentifier=pexi-${j.name}`);
  return `${L.join('\n')}\n`;
}

function timer(j) {
  const L = [];
  L.push(`# Generated by linux/make-units.mjs; edit the table there, not this file.`);
  L.push(`# launchd twin: ${j.twin}. Times are the server's local time (America/Toronto), same as the Mac.`);
  L.push('');
  L.push('[Unit]');
  L.push(`Description=Pexi ${j.name} schedule`);
  L.push('');
  L.push('[Timer]');
  if (j.every) {
    L.push('OnBootSec=60s');
    L.push(`OnUnitActiveSec=${j.every}`);
  } else {
    L.push(`OnCalendar=${j.when}`);
    // Like launchd, a run missed because the box was off or rebooting happens at the next start.
    L.push('Persistent=true');
  }
  L.push('AccuracySec=1s');
  L.push(`Unit=pexi-${j.name}.service`);
  L.push('');
  L.push('[Install]');
  L.push('WantedBy=timers.target');
  return `${L.join('\n')}\n`;
}

export function render() {
  const files = {};
  for (const j of JOBS) {
    files[`pexi-${j.name}.service`] = service(j);
    files[`pexi-${j.name}.timer`] = timer(j);
  }
  return files;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())) {
  const files = render();
  if (process.argv.includes('--check')) {
    const stale = [];
    for (const [name, text] of Object.entries(files)) {
      let have = null;
      try { have = readFileSync(join(OUT, name), 'utf8'); } catch { /* missing */ }
      if (have !== text) stale.push(name);
    }
    if (stale.length) {
      console.error(`out of date: ${stale.join(', ')}; run node linux/make-units.mjs`);
      process.exit(1);
    }
    console.log(`${Object.keys(files).length} unit files current`);
  } else {
    mkdirSync(OUT, { recursive: true });
    for (const [name, text] of Object.entries(files)) writeFileSync(join(OUT, name), text);
    console.log(`wrote ${Object.keys(files).length} unit files to ${OUT}`);
  }
}
