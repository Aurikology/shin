// Lighten (positive) or darken (negative) a hex colour. amount is -1..1.
function tint(hex, amount) {
  const clean = hex.replace('#', '')
  const full = clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean
  const num = parseInt(full, 16)
  let r = (num >> 16) & 0xff
  let g = (num >> 8) & 0xff
  let b = num & 0xff
  const adjust = (c) => (amount >= 0 ? c + (255 - c) * amount : c * (1 + amount))
  r = Math.min(255, Math.max(0, Math.round(adjust(r))))
  g = Math.min(255, Math.max(0, Math.round(adjust(g))))
  b = Math.min(255, Math.max(0, Math.round(adjust(b))))
  const toHex = (c) => c.toString(16).padStart(2, '0')
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`
}

// Draws one icon onto a fresh canvas at size by size pixels, scaled up from the 16 by 16 map.
export function iconCanvas(name, size, colours = {}) {
  const map = ICONS[name] || ICONS.unknown
  const body = colours.body || '#F7F5F2'
  const ground = colours.ground || '#0B0C0E'
  const scale = Math.max(1, Math.floor(size / 16))

  const canvas = document.createElement('canvas')
  canvas.width = size
  canvas.height = size
  canvas.style.width = `${size}px`
  canvas.style.height = `${size}px`
  canvas.style.imageRendering = 'pixelated'

  const palette = {
    '.': null,
    O: ground,
    B: body,
    H: tint(body, 0.3),
    S: tint(body, -0.3),
    W: '#F7F5F2',
    Y: '#FFC24D',
    C: '#7FD1FF',
    R: '#FF6A45',
  }

  const ctx = canvas.getContext('2d')
  for (let y = 0; y < 16; y++) {
    const row = map[y]
    for (let x = 0; x < 16; x++) {
      const fill = palette[row[x]]
      if (!fill) continue
      ctx.fillStyle = fill
      ctx.fillRect(x * scale, y * scale, scale, scale)
    }
  }
  return canvas
}
